class GrowthMeasurement {
  final String dateString;
  final DateTime date;
  final int ageMonths;
  final double weightKg;
  final double lengthCm;
  final double headCircumferenceCm;
  final double zScore;
  final String eventType;
  final String workerName;
  final String notes;

  GrowthMeasurement({
    required this.dateString,
    DateTime? date,
    required this.ageMonths,
    required this.weightKg,
    required this.lengthCm,
    this.headCircumferenceCm = 46.5,
    required this.zScore,
    required this.eventType,
    required this.workerName,
    required this.notes,
  }) : date = date ?? _parseDate(dateString);

  static DateTime _parseDate(String str) {
    final months = {
      'jan': 1, 'feb': 2, 'mar': 3, 'apr': 4, 'may': 5, 'jun': 6,
      'jul': 7, 'aug': 8, 'sep': 9, 'oct': 10, 'nov': 11, 'dec': 12,
    };
    try {
      final parts = str.trim().split(RegExp(r'\s+'));
      if (parts.length >= 3) {
        final day = int.tryParse(parts[0]) ?? 1;
        final mStr = parts[1].toLowerCase().substring(0, 3);
        final month = months[mStr] ?? 1;
        final year = int.tryParse(parts[2]) ?? 2026;
        return DateTime(year, month, day);
      }
    } catch (_) {}
    return DateTime.now();
  }

  GrowthMeasurement copyWith({
    String? dateString,
    DateTime? date,
    int? ageMonths,
    double? weightKg,
    double? lengthCm,
    double? headCircumferenceCm,
    double? zScore,
    String? eventType,
    String? workerName,
    String? notes,
  }) {
    return GrowthMeasurement(
      dateString: dateString ?? this.dateString,
      date: date ?? this.date,
      ageMonths: ageMonths ?? this.ageMonths,
      weightKg: weightKg ?? this.weightKg,
      lengthCm: lengthCm ?? this.lengthCm,
      headCircumferenceCm: headCircumferenceCm ?? this.headCircumferenceCm,
      zScore: zScore ?? this.zScore,
      eventType: eventType ?? this.eventType,
      workerName: workerName ?? this.workerName,
      notes: notes ?? this.notes,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'dateString': dateString,
      'date': date.toIso8601String(),
      'ageMonths': ageMonths,
      'weightKg': weightKg,
      'lengthCm': lengthCm,
      'headCircumferenceCm': headCircumferenceCm,
      'zScore': zScore,
      'eventType': eventType,
      'workerName': workerName,
      'notes': notes,
    };
  }

  factory GrowthMeasurement.fromJson(Map<String, dynamic> json) {
    return GrowthMeasurement(
      dateString: json['dateString'] as String? ?? '12 Feb 2026',
      date: json['date'] != null ? DateTime.tryParse(json['date'] as String) : null,
      ageMonths: json['ageMonths'] as int? ?? 14,
      weightKg: (json['weightKg'] as num?)?.toDouble() ?? 9.4,
      lengthCm: (json['lengthCm'] as num?)?.toDouble() ?? 77.2,
      headCircumferenceCm: (json['headCircumferenceCm'] as num?)?.toDouble() ?? 46.5,
      zScore: (json['zScore'] as num?)?.toDouble() ?? 0.0,
      eventType: json['eventType'] as String? ?? 'Routine Checkup',
      workerName: json['workerName'] as String? ?? 'Kavita Ben',
